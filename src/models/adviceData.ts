/**
 * Returns today's advice based on calendar day of month or year
 */
export function getDailyAdvice(customDate?: Date): DailyAdvice {
  const date = customDate || new Date();
  // Using day of month (1-31)
  const dayOfMonth = date.getDate();
  const found = DAILY_ADVICE_LIST.find(a => a.dayIndex === dayOfMonth);
  return found || DAILY_ADVICE_LIST[(dayOfMonth - 1) % DAILY_ADVICE_LIST.length];
}
